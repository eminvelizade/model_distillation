#!/usr/bin/env bash
# Regenerate the agent's hash-pinned lock files from environment.yml (run after changing the pins there).
#
#   requirements-agent.lock   environment.yml's pip pins + cryptography (release signature checks), with hashes
#   requirements-vendor.lock  albumentations 1.4.24 for rfdetr (installed into vendor/albumentations14, see setup_env.sh)
#
# Agents build their environment with `uv pip install --require-hashes --no-deps -r requirements-agent.lock`, so
# every PC gets byte-identical packages. Needs uv and network access to PyPI and download.pytorch.org.
set -euo pipefail
cd "$(dirname "$0")"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

grep -E '^\s+- [^ ]+==' environment.yml | sed -E 's/^\s+- //' > "$tmp/pins.in"
echo "cryptography" >> "$tmp/pins.in"
uv pip compile "$tmp/pins.in" --generate-hashes --python-version 3.11 --python-platform x86_64-manylinux_2_28 \
  --extra-index-url https://download.pytorch.org/whl/cu128 --index-strategy unsafe-best-match \
  --no-header --quiet -o "$tmp/agent.lock"
{ echo "# Generated by lock_agent_env.sh from environment.yml (+ cryptography). Do not edit by hand."
  cat "$tmp/agent.lock"; } > requirements-agent.lock

printf 'albumentations==1.4.24\nalbucore==0.0.23\nsimsimd==6.5.16\nstringzilla==5.3.2\n' > "$tmp/vendor.in"
uv pip compile "$tmp/vendor.in" --no-deps --generate-hashes --python-version 3.11 --python-platform x86_64-manylinux_2_28 \
  --no-header --quiet -o "$tmp/vendor.lock"
{ echo "# Generated by lock_agent_env.sh: albumentations for rfdetr (vendor/albumentations14). Do not edit by hand."
  cat "$tmp/vendor.lock"; } > requirements-vendor.lock

echo "requirements-agent.lock: $(grep -c '==' requirements-agent.lock) packages; requirements-vendor.lock: $(grep -c '==' requirements-vendor.lock)"
